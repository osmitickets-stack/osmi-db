-- A paid order and its ticket email job are committed in the same transaction.
-- The job stores no QR, message body, SMTP credential, or recipient address.
CREATE TABLE notifications.ticket_email_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL UNIQUE REFERENCES billing.orders(id) ON DELETE CASCADE,
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'sending', 'retrying', 'accepted',
                         'delayed', 'delivered', 'bounced', 'complained',
                         'rejected', 'exhausted')),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0 AND attempts <= 5),
    next_attempt_at timestamptz,
    lease_until timestamptz,
    current_attempt_id uuid,
    last_event_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE notifications.ticket_email_attempts (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    job_id bigint NOT NULL REFERENCES notifications.ticket_email_jobs(id) ON DELETE CASCADE,
    attempt_number integer NOT NULL CHECK (attempt_number BETWEEN 1 AND 5),
    status text NOT NULL DEFAULT 'sending'
        CHECK (status IN ('sending', 'transport_failed', 'accepted', 'delayed',
                         'delivered', 'bounced', 'complained', 'rejected')),
    ses_message_id text,
    error_code text,
    accepted_at timestamptz,
    last_event_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (job_id, attempt_number)
);

CREATE INDEX ticket_email_jobs_due_idx
    ON notifications.ticket_email_jobs (next_attempt_at, id)
    WHERE status IN ('pending', 'retrying');
CREATE INDEX ticket_email_jobs_expired_lease_idx
    ON notifications.ticket_email_jobs (lease_until, id)
    WHERE status = 'sending';
CREATE INDEX ticket_email_attempts_ses_message_idx
    ON notifications.ticket_email_attempts (ses_message_id)
    WHERE ses_message_id IS NOT NULL;

CREATE TABLE notifications.email_suppressions (
    recipient_sha256 char(64) PRIMARY KEY,
    reason text NOT NULL CHECK (reason IN ('bounce', 'complaint')),
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
