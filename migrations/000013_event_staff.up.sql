-- =============================================================================
-- OSMI DATABASE
-- Migración 000013 — Event Staff Authorization
-- =============================================================================
--
-- Propósito:
--   - Asignar usuarios autenticados a eventos concretos.
--   - Separar roles globales de permisos scoped por evento.
--   - Permitir autorización segura para check-in.
--
-- Roles iniciales:
--   - event_manager
--   - checkin_staff
--
-- El owner del evento NO se duplica aquí.
-- Se resuelve mediante:
--
-- auth.users.id
--      ↓
-- ticketing.organizers.user_id
--      ↓
-- ticketing.events.organizer_id
--
-- Dependencias:
--   - 000002_auth
--   - 000004_ticketing
--
-- =============================================================================


-- =============================================================================
-- 1. TABLA
-- =============================================================================

CREATE TABLE ticketing.event_staff (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    event_id bigint NOT NULL,
    user_id bigint NOT NULL,

    role character varying(30) NOT NULL,

    is_active boolean NOT NULL DEFAULT true,

    granted_by bigint,
    revoked_by bigint,

    granted_at timestamp with time zone NOT NULL DEFAULT now(),
    revoked_at timestamp with time zone,

    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT event_staff_role_check
        CHECK (
            role IN (
                'event_manager',
                'checkin_staff'
            )
        ),

    CONSTRAINT event_staff_event_user_key
        UNIQUE (event_id, user_id),

    CONSTRAINT event_staff_event_id_fkey
        FOREIGN KEY (event_id)
        REFERENCES ticketing.events(id)
        ON DELETE CASCADE,

    CONSTRAINT event_staff_user_id_fkey
        FOREIGN KEY (user_id)
        REFERENCES auth.users(id)
        ON DELETE CASCADE,

    CONSTRAINT event_staff_granted_by_fkey
        FOREIGN KEY (granted_by)
        REFERENCES auth.users(id)
        ON DELETE SET NULL,

    CONSTRAINT event_staff_revoked_by_fkey
        FOREIGN KEY (revoked_by)
        REFERENCES auth.users(id)
        ON DELETE SET NULL
);


-- =============================================================================
-- 2. ÍNDICES
-- =============================================================================

CREATE INDEX idx_event_staff_event_id
    ON ticketing.event_staff(event_id);

CREATE INDEX idx_event_staff_user_id
    ON ticketing.event_staff(user_id);

CREATE INDEX idx_event_staff_event_active
    ON ticketing.event_staff(event_id, is_active);

CREATE INDEX idx_event_staff_user_active
    ON ticketing.event_staff(user_id, is_active);

CREATE INDEX idx_event_staff_active_role
    ON ticketing.event_staff(event_id, user_id, role)
    WHERE is_active = true;


-- =============================================================================
-- 3. TRIGGER updated_at
-- =============================================================================

CREATE TRIGGER trg_update_event_staff
BEFORE UPDATE ON ticketing.event_staff
FOR EACH ROW
EXECUTE FUNCTION auth.update_updated_at();


